import type { PolicyBlock } from "@/features/settings/model/types";

type PolicyDocumentData = {
  title: string;
  blocks: PolicyBlock[];
};

function stripBold(value: string): string {
  return value.replace(/\*\*/g, "");
}

function parseTable(lines: string[]): PolicyBlock {
  const [headerLine, , ...rowLines] = lines;
  const parseRow = (line: string) =>
    line
      .split("|")
      .slice(1, -1)
      .map((cell) => stripBold(cell.trim()));

  return {
    type: "table",
    headers: parseRow(headerLine),
    rows: rowLines.map(parseRow),
  };
}

function parsePolicy(source: string): PolicyBlock[] {
  const blocks: PolicyBlock[] = [];
  const lines = source.split("\n");
  let index = 0;

  while (index < lines.length) {
    const line = lines[index].trim();

    if (!line) {
      index += 1;
      continue;
    }

    if (line.startsWith("|")) {
      const tableLines: string[] = [];
      while (index < lines.length && lines[index].trim().startsWith("|")) {
        tableLines.push(lines[index].trim());
        index += 1;
      }
      blocks.push(parseTable(tableLines));
      continue;
    }

    const headingMatch = /^(#{1,3})\s+(.+)$/.exec(line);
    if (headingMatch) {
      blocks.push({
        type: "heading",
        level: headingMatch[1].length as 1 | 2 | 3,
        text: stripBold(headingMatch[2]),
      });
      index += 1;
      continue;
    }

    if (line.startsWith("**※") || line.startsWith("※")) {
      blocks.push({ type: "note", text: stripBold(line) });
      index += 1;
      continue;
    }

    if (/^\d+\.\s+/.test(line)) {
      const items: string[] = [];
      while (index < lines.length && /^\d+\.\s+/.test(lines[index].trim())) {
        items.push(stripBold(lines[index].trim().replace(/^\d+\.\s+/, "")));
        index += 1;
      }
      blocks.push({ type: "orderedList", items });
      continue;
    }

    if (line.startsWith("- ")) {
      const items: string[] = [];
      while (index < lines.length && lines[index].trim().startsWith("- ")) {
        items.push(stripBold(lines[index].trim().slice(2)));
        index += 1;
      }
      blocks.push({ type: "bulletList", items });
      continue;
    }

    blocks.push({ type: "paragraph", text: stripBold(line) });
    index += 1;
  }

  return blocks;
}

